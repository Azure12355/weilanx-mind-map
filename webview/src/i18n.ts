let current: Record<Key, string> = zh;
let isZh = true;

export function setLang(lang: string) {
  isZh = lang.toLowerCase().startsWith("zh");
  current = isZh ? zh : en;
}

export function t(key: Key, ...args: (string | number)[]): string {
  return current[key].replace(/\{(\d)\}/g, (_m, i) => String(args[Number(i)] ?? ""));
}

export function langIsZh() {
  return isZh;
}
